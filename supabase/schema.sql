create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a
    where lower(a.email) = lower((select auth.jwt() ->> 'email'))
  );
$$;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

drop policy if exists products_public_read on public.products;
create policy products_public_read on public.products for select to anon using (active);
drop policy if exists products_authenticated_read on public.products;
create policy products_authenticated_read on public.products for select to authenticated
  using (active or (select public.is_admin()));
drop policy if exists products_admin_update on public.products;
create policy products_admin_update on public.products for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists orders_admin_read on public.orders;
create policy orders_admin_read on public.orders for select to authenticated
  using ((select public.is_admin()));
drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists order_items_admin_read on public.order_items;
create policy order_items_admin_read on public.order_items for select to authenticated
  using ((select public.is_admin()));

revoke all on public.products, public.admin_users, public.orders, public.order_items, public.order_rate_limits from anon, authenticated;
grant select on public.products to anon, authenticated;
grant select on public.orders, public.order_items to authenticated;
grant update (name, price, active) on public.products to authenticated;
grant update (status) on public.orders to authenticated;
grant all on public.products, public.admin_users, public.orders, public.order_items, public.order_rate_limits to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.consume_order_rate(p_ip_hash text)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare
  v_attempts integer;
begin
  if p_ip_hash is null or char_length(p_ip_hash) <> 64 then return false; end if;
  delete from public.order_rate_limits where window_started < now() - interval '2 days';
  insert into public.order_rate_limits(ip_hash, window_started, request_count) values (p_ip_hash, now(), 1)
  on conflict (ip_hash) do update set
    window_started = case when public.order_rate_limits.window_started < now() - interval '10 minutes' then now() else public.order_rate_limits.window_started end,
    request_count = case when public.order_rate_limits.window_started < now() - interval '10 minutes' then 1 else public.order_rate_limits.request_count + 1 end
  returning request_count into v_attempts;
  return v_attempts <= 8;
end;
$$;
revoke all on function public.consume_order_rate(text) from public, anon, authenticated;
grant execute on function public.consume_order_rate(text) to service_role;

