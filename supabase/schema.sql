create or replace function public.create_customer_order(
  p_name text, p_phone text, p_delivery text, p_address text, p_payment text, p_items jsonb
)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_total integer := 0;
  v_items jsonb;
begin
  if p_name is null or char_length(trim(p_name)) not between 1 and 80 then
    raise exception 'Escribe un nombre válido.' using errcode = '22023';
  end if;
  if p_phone is null or char_length(trim(p_phone)) not between 7 and 30
     or trim(p_phone) !~ '^[+0-9 ()-]{7,30}$'
     or char_length(regexp_replace(p_phone, '[^0-9]', '', 'g')) < 7 then
    raise exception 'Escribe un teléfono válido.' using errcode = '22023';
  end if;
  if p_delivery not in ('Recojo en el local', 'Entrega a domicilio') or p_payment not in ('Efectivo', 'QR') then
    raise exception 'La forma de entrega o pago no es válida.' using errcode = '22023';
  end if;
  if p_delivery = 'Entrega a domicilio' and (p_address is null or char_length(trim(p_address)) not between 1 and 250) then
    raise exception 'Escribe la dirección y zona.' using errcode = '22023';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 20 then
    raise exception 'Agrega productos al pedido.' using errcode = '22023';
  end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    if jsonb_typeof(v_item) <> 'object' or coalesce(v_item->>'id', '') = '' or coalesce(v_item->>'quantity', '') !~ '^[0-9]+$' then
      raise exception 'Hay un producto o cantidad inválida.' using errcode = '22023';
    end if;
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity not between 1 and 50 then raise exception 'La cantidad no es válida.' using errcode = '22023'; end if;
    select * into v_product from public.products where id = v_item->>'id' and active = true for share;
    if not found then raise exception 'Uno de los productos no está disponible.' using errcode = '22023'; end if;
    v_total := v_total + v_product.price * v_quantity;
  end loop;
  if v_total > 100000 then raise exception 'El total supera el máximo permitido.' using errcode = '22023'; end if;

  insert into public.orders(customer_name, customer_phone, delivery, address, payment, total)
  values (trim(p_name), trim(p_phone), p_delivery,
          case when p_delivery = 'Entrega a domicilio' then trim(p_address) else '' end,
          p_payment, v_total)
  returning * into v_order;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_quantity := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id = v_item->>'id' and active = true for share;
    insert into public.order_items(order_id, product_id, product_name, quantity, unit_price)
    values (v_order.id, v_product.id, v_product.name, v_quantity, v_product.price);
  end loop;
  select jsonb_agg(jsonb_build_object('id', product_id, 'name', product_name, 'quantity', quantity, 'price', unit_price) order by id)
    into v_items from public.order_items where order_id = v_order.id;
  return jsonb_build_object(
    'id', v_order.id, 'customer_name', v_order.customer_name, 'customer_phone', v_order.customer_phone,
    'delivery', v_order.delivery, 'address', v_order.address, 'payment', v_order.payment,
    'total', v_order.total, 'status', v_order.status, 'created_at', v_order.created_at, 'items', v_items
  );
end;
$$;
revoke all on function public.create_customer_order(text, text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.create_customer_order(text, text, text, text, text, jsonb) to service_role;

