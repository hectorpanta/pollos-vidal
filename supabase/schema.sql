create table if not exists public.products (
  id text primary key,
  name text not null check (char_length(name) between 1 and 80),
  description text not null default '',
  price integer not null check (price between 0 and 10000),
  active boolean not null default true
);
create table if not exists public.admin_users (
  email text primary key,
  display_name text not null
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  delivery text not null check (delivery in ('Recojo en el local', 'Entrega a domicilio')),
  address text not null default '',
  payment text not null check (payment in ('Efectivo', 'QR')),
  total integer not null check (total >= 0),
  status text not null default 'nuevo' check (status in ('nuevo', 'confirmado', 'preparando', 'listo', 'entregado', 'cancelado')),
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id text not null,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 50),
  unit_price integer not null check (unit_price >= 0)
);
create table if not exists public.order_rate_limits (
  ip_hash text primary key,
  window_started timestamptz not null default now(),
  request_count integer not null default 0
);

